--   MULTISET / table options / COMPRESS / FORMAT / NOT CASESPECIFIC / stats / NUSI -> removed
--   UNIQUE PRIMARY INDEX (ACCOUNT_KEY)     -> CLUSTER BY ACCOUNT_KEY (+ NUPI ACCOUNT_ID)
--   PPI RANGE_N(OPENING_DATE ... EACH INTERVAL '1' YEAR)
--                                          -> PARTITION BY DATE_TRUNC(OPENING_DATE, YEAR)
--   GENERATED ALWAYS AS IDENTITY           -> plain INT64 assigned at load
--   DECIMAL(p,s)                           -> NUMERIC(p,s); BYTEINT -> INT64
CREATE TABLE IF NOT EXISTS banking_dw.dim_account_history (
    ACCOUNT_KEY         INT64     NOT NULL,
    ACCOUNT_ID          STRING    NOT NULL,
    CUSTOMER_ID         INT64     NOT NULL,
    ACCOUNT_TYPE        STRING    NOT NULL,
    ACCOUNT_SUBTYPE     STRING,
    CURRENCY_CODE       STRING    DEFAULT 'NOK',
    OPENING_DATE        DATE      NOT NULL,
    CLOSING_DATE        DATE,
    ACCOUNT_STATUS      STRING    DEFAULT 'ACTIVE',
    INTEREST_RATE       NUMERIC(7, 4),
    CREDIT_LIMIT        NUMERIC(15, 2),
    OVERDRAFT_LIMIT     NUMERIC(15, 2) DEFAULT 0,
    BRANCH_ID           INT64,
    RELATIONSHIP_MGR_ID INT64,
    PRODUCT_ID          INT64     NOT NULL,
    IS_JOINT_ACCOUNT    INT64     DEFAULT 0,
    TAX_REPORTING_FLAG  INT64     DEFAULT 1,
    EFFECTIVE_FROM      TIMESTAMP DEFAULT CURRENT_TIMESTAMP(),
    EFFECTIVE_TO        TIMESTAMP DEFAULT TIMESTAMP '9999-12-31 23:59:59+00',
    CURRENT_FLAG        STRING    DEFAULT 'Y',
    ETL_BATCH_ID        INT64,
    ETL_INSERT_TS       TIMESTAMP DEFAULT CURRENT_TIMESTAMP(),
    ETL_UPDATE_TS       TIMESTAMP DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (ACCOUNT_KEY) NOT ENFORCED
)
PARTITION BY DATE_TRUNC(OPENING_DATE, YEAR)
CLUSTER BY ACCOUNT_KEY, ACCOUNT_ID, CUSTOMER_ID, CURRENT_FLAG
OPTIONS (description = 'Account dimension with SCD Type 2 tracking for status and rate changes');
