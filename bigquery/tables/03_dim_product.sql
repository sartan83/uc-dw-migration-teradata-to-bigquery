--   UNIQUE PRIMARY INDEX (PRODUCT_ID) -> CLUSTER BY PRODUCT_ID + PRIMARY KEY NOT ENFORCED
--   No PPI -> unpartitioned (small dimension)
CREATE TABLE IF NOT EXISTS banking_dw.dim_product (
    PRODUCT_ID          INT64     NOT NULL,
    PRODUCT_CODE        STRING    NOT NULL,
    PRODUCT_NAME        STRING    NOT NULL,
    PRODUCT_CATEGORY    STRING    NOT NULL,
    PRODUCT_SUBCATEGORY STRING,
    BASE_INTEREST_RATE  NUMERIC(7, 4),
    MIN_BALANCE         NUMERIC(15, 2) DEFAULT 0,
    MAX_BALANCE         NUMERIC(15, 2),
    FEE_STRUCTURE       STRING,
    MONTHLY_FEE         NUMERIC(10, 2) DEFAULT 0,
    IS_REGULATED        INT64     DEFAULT 1,
    REGULATORY_CODE     STRING,
    LAUNCH_DATE         DATE,
    DISCONTINUE_DATE    DATE,
    IS_ACTIVE           INT64     DEFAULT 1,
    ETL_BATCH_ID        INT64,
    ETL_INSERT_TS       TIMESTAMP DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (PRODUCT_ID) NOT ENFORCED
)
CLUSTER BY PRODUCT_ID
OPTIONS (description = 'Banking product catalog dimension');
