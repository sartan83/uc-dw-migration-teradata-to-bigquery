--         (Teradata MULTISET TABLE BANKING_DW.FACT_MONTHLY_ACCOUNT_SNAPSHOT)
--   MULTISET / table options / COMPRESS / FORMAT / stats -> removed
--   PRIMARY INDEX (ACCOUNT_KEY, SNAPSHOT_MONTH_KEY) -> CLUSTER BY ACCOUNT_KEY, SNAPSHOT_MONTH_KEY
--   PPI RANGE_N(SNAPSHOT_DATE ... EACH INTERVAL '1' MONTH, NO RANGE)
--                                  -> PARTITION BY DATE_TRUNC(SNAPSHOT_DATE, MONTH)
--   SMALLINT -> INT64; DECIMAL -> NUMERIC
-- Added: ACCOUNT_ID / CUSTOMER_ID natural keys (filled by sp_monthly_snapshot).
CREATE TABLE IF NOT EXISTS banking_dw.fact_monthly_account_snapshot (
    SNAPSHOT_DATE         DATE      NOT NULL,
    SNAPSHOT_MONTH_KEY    INT64     NOT NULL OPTIONS (description = 'YYYYMM'),
    ACCOUNT_KEY           INT64     NOT NULL,
    CUSTOMER_KEY          INT64     NOT NULL,
    ACCOUNT_ID            STRING    NOT NULL,
    CUSTOMER_ID           INT64     NOT NULL,
    PRODUCT_ID            INT64     NOT NULL,
    BRANCH_ID             INT64,
    OPENING_BALANCE       NUMERIC(15, 2) NOT NULL,
    CLOSING_BALANCE       NUMERIC(15, 2) NOT NULL,
    AVERAGE_BALANCE       NUMERIC(15, 2),
    MINIMUM_BALANCE       NUMERIC(15, 2),
    MAXIMUM_BALANCE       NUMERIC(15, 2),
    TOTAL_DEBITS          NUMERIC(15, 2) DEFAULT 0,
    TOTAL_CREDITS         NUMERIC(15, 2) DEFAULT 0,
    DEBIT_COUNT           INT64     DEFAULT 0,
    CREDIT_COUNT          INT64     DEFAULT 0,
    INTEREST_EARNED       NUMERIC(12, 2) DEFAULT 0,
    INTEREST_CHARGED      NUMERIC(12, 2) DEFAULT 0,
    FEES_CHARGED          NUMERIC(12, 2) DEFAULT 0,
    DAYS_IN_OVERDRAFT     INT64     DEFAULT 0,
    DAYS_DORMANT          INT64     DEFAULT 0,
    CURRENCY_CODE         STRING    DEFAULT 'NOK',
    BASE_CURRENCY_CLOSING NUMERIC(15, 2),
    ETL_BATCH_ID          INT64,
    ETL_INSERT_TS         TIMESTAMP DEFAULT CURRENT_TIMESTAMP()
)
PARTITION BY DATE_TRUNC(SNAPSHOT_DATE, MONTH)
CLUSTER BY ACCOUNT_KEY, SNAPSHOT_MONTH_KEY, ACCOUNT_ID, BRANCH_ID
OPTIONS (description = 'Monthly periodic snapshot: one row per account per calendar month');
