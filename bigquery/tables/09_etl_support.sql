-- Staging, control and logging tables referenced by the Teradata procedures and
-- BTEQ scripts (BANKING_DW.STG_*, ETL_LOG, ETL_BATCH_CONTROL, DIM_EXCHANGE_RATES).
-- Their Teradata DDL is not in ddl/tables/; the shapes below are inferred from
-- the columns the DML reads and writes.
CREATE TABLE IF NOT EXISTS banking_dw.stg_customer (
    CUSTOMER_ID      INT64 NOT NULL,
    FIRST_NAME       STRING,
    LAST_NAME        STRING,
    DATE_OF_BIRTH    DATE,
    GENDER           STRING,
    MARITAL_STATUS   STRING,
    EMAIL_ADDRESS    STRING,
    PHONE_NUMBER     STRING,
    ADDRESS_LINE_1   STRING,
    ADDRESS_LINE_2   STRING,
    CITY             STRING,
    STATE_PROVINCE   STRING,
    POSTAL_CODE      STRING,
    COUNTRY_CODE     STRING,
    CUSTOMER_SEGMENT STRING,
    RISK_SCORE       NUMERIC(5, 2),
    CREDIT_RATING    STRING,
    KYC_STATUS       STRING
);

CREATE TABLE IF NOT EXISTS banking_dw.stg_transactions (
    LOAD_DATE           DATE   NOT NULL,
    TRANSACTION_ID      INT64  NOT NULL,
    TRANSACTION_DATE    DATE   NOT NULL,
    TRANSACTION_TIME    TIME,
    ACCOUNT_ID          STRING,
    TRANSACTION_TYPE    STRING,
    TRANSACTION_SUBTYPE STRING,
    CHANNEL             STRING,
    TRANSACTION_AMOUNT  NUMERIC(15, 2),
    CURRENCY_CODE       STRING,
    MERCHANT_ID         STRING,
    MERCHANT_NAME       STRING,
    MERCHANT_CATEGORY   STRING,
    COUNTERPARTY_ACCT   STRING,
    REFERENCE_NUMBER    STRING,
    DESCRIPTION_TEXT    STRING,
    POSTING_DATE        DATE,
    VALUE_DATE          DATE
)
PARTITION BY LOAD_DATE;

CREATE TABLE IF NOT EXISTS banking_dw.stg_transaction_errors (
    LOAD_DATE           DATE,
    TRANSACTION_ID      INT64,
    TRANSACTION_DATE    DATE,
    TRANSACTION_TIME    TIME,
    ACCOUNT_ID          STRING,
    TRANSACTION_TYPE    STRING,
    TRANSACTION_SUBTYPE STRING,
    CHANNEL             STRING,
    TRANSACTION_AMOUNT  NUMERIC(15, 2),
    CURRENCY_CODE       STRING,
    MERCHANT_ID         STRING,
    MERCHANT_NAME       STRING,
    MERCHANT_CATEGORY   STRING,
    COUNTERPARTY_ACCT   STRING,
    REFERENCE_NUMBER    STRING,
    DESCRIPTION_TEXT    STRING,
    POSTING_DATE        DATE,
    VALUE_DATE          DATE,
    ERROR_REASON        STRING,
    BATCH_ID            INT64
)
PARTITION BY LOAD_DATE;

CREATE TABLE IF NOT EXISTS banking_dw.dim_exchange_rates (
    RATE_DATE     DATE   NOT NULL,
    FROM_CURRENCY STRING NOT NULL,
    TO_CURRENCY   STRING NOT NULL,
    EXCHANGE_RATE NUMERIC(12, 6)
)
CLUSTER BY FROM_CURRENCY, RATE_DATE;

CREATE TABLE IF NOT EXISTS banking_dw.etl_log (
    PROCEDURE_NAME STRING,
    BATCH_ID       INT64,
    LOG_LEVEL      STRING,
    LOG_MESSAGE    STRING,
    LOG_TS         TIMESTAMP
)
PARTITION BY DATE(LOG_TS);

CREATE TABLE IF NOT EXISTS banking_dw.etl_batch_control (
    BATCH_ID     INT64 NOT NULL,
    BATCH_DATE   DATE,
    BATCH_STATUS STRING,
    START_TS     TIMESTAMP,
    END_TS       TIMESTAMP
);
